"""标题标签分类器：按政策标题关键字匹配，返回所有命中标签。

纯函数，无 LLM、无 IO。供 policy_radar RSS 端点在构建 item 时实时调用，
merge 源级标签（PolicySource.tags）使用。不落库、不加 Policy.tags 列。

标签顺序：先匹配更具体的文旅专属标签，再匹配通用公文类型。
一条政策可命中多个标签（如「关于印发十四五文旅规划的通知」-> 文旅_规划 + 政策文件 + 通知）。
"""

from __future__ import annotations


# 标签 -> 触发关键字（标题含即命中）。顺序即匹配优先级，但都收集进结果。
_TAG_RULES: list[tuple[str, list[str]]] = [
    # 文旅专属（具体优先）
    ("文旅_规划", ["十五五", "十四五", "十三五", "五年规划", "发展规划", "实施方案", "总体规划", "空间规划"]),
    ("文旅_申报", ["申报", "试点申报", "项目申报", "资金申报", "申报通知", "征集", "推荐申报"]),
    ("文旅_非遗", ["非遗", "非物质文化遗产", "传统工艺", "传承人"]),
    ("文旅_文物", ["文物", "考古", "遗产保护", "博物馆", "不可移动"]),
    ("文旅_广电", ["广电", "广播电视", "网络视听", "电视剧", "动画片"]),
    ("文旅_体育", ["体育", "全民健身", "赛事", "马拉松", "冰雪运动"]),
    ("文旅_政策", ["文旅", "旅游", "文化", "景区", "演出", "民宿", "乡村旅游"]),
    # 通用公文类型
    ("解读", ["解读", "一图读懂", "问答", "答记者问", "答问"]),
    ("会议", ["会议", "常务会议", "全体会议", "专题会议", "党组会议"]),
    ("公告", ["公告", "公示", "招录", "招聘", "评选", "遴选"]),
    ("通知", ["通知", "通报", "转发"]),
    ("法规", ["法规", "规章", "条例"]),
    ("政策文件", ["办法", "规定", "细则", "意见", "决定", "规划", "方案"]),
    ("公文", ["批复", "函", "请示", "报告", "令"]),
]


def classify_tags(title: str) -> list[str]:
    """对政策标题分类，返回所有命中标签（去重，保持命中顺序）。

    Args:
        title: 政策标题

    Returns:
        命中标签列表，如 ["文旅_规划", "政策文件"]。无命中返回 ["新闻动态"]。
    """
    if not title:
        return []
    title = title.strip()
    hit: list[str] = []
    for tag, keywords in _TAG_RULES:
        if any(kw in title for kw in keywords):
            if tag not in hit:
                hit.append(tag)
    if not hit:
        hit.append("新闻动态")
    return hit
